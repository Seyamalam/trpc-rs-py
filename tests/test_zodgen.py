"""Tests for `trpc_rs_py.zodgen.generate_zod` — Zod v4 schema emission."""

from __future__ import annotations

import datetime
import uuid
from enum import Enum
from typing import Annotated, Literal

import pytest
from pydantic import BaseModel, Field, PlainSerializer, StringConstraints

from trpc_rs_py import Router
from trpc_rs_py.zodgen import _js_regex, generate_zod


class Color(Enum):
    """Str enum for the enum-mapping test."""

    RED = "red"
    BLUE = "blue"


class Cat(BaseModel):
    """Discriminated-union member sharing `kind`."""

    kind: Literal["cat"]
    meows: bool


class Dog(BaseModel):
    """Second discriminated-union member."""

    kind: Literal["dog"]
    barks: bool


class Inner(BaseModel):
    """Nested model for the const-emission test."""

    x: Annotated[int, Field(ge=0)]


def make_router() -> Router:
    """Build a small router exercising the core zod mappings."""
    router = Router()

    @router.query
    def greet(name: str, punctuation: str = "!") -> str:
        return name + punctuation

    return router


def test_header_and_import() -> None:
    """Every module starts with the generated banner and the zod import."""
    out = generate_zod(make_router())
    assert out.startswith("// Generated by `trpc-py codegen zod`")
    assert 'import { z } from "zod";' in out


def test_scalar_input_object() -> None:
    """Procedure params become `z.object` members; defaults → `.default`."""
    out = generate_zod(make_router())
    assert "export const GreetInput = z.object({" in out
    assert "  name: z.string()," in out
    assert '  punctuation: z.string().default("!"),' in out


def test_no_input_procedure_gets_comment() -> None:
    """A procedure with no params emits a comment, not an empty schema."""
    router = Router()

    @router.query
    def health() -> str:
        return "ok"

    assert "// procedure 'health' takes no input" in generate_zod(router)


def test_primitive_map() -> None:
    """Int → `.int()`, float → `z.number()`, bool → `z.boolean()`."""
    router = Router()

    @router.query
    def f(i: int, x: float, b: bool) -> str:
        return ""

    out = generate_zod(router)
    assert "i: z.number().int()," in out
    assert "x: z.number()," in out
    assert "b: z.boolean()," in out


def test_numeric_constraints() -> None:
    """Field(gt/ge/lt/le) and MultipleOf map to zod number methods."""
    router = Router()

    @router.query
    def f(
        a: Annotated[int, Field(gt=0, le=10)],
        b: Annotated[float, Field(multiple_of=0.5)],
    ) -> str:
        return ""

    out = generate_zod(router)
    assert "a: z.number().int().gt(0).lte(10)," in out
    assert "b: z.number().multipleOf(0.5)," in out


def test_string_constraints() -> None:
    """StringConstraints map min/max length and pattern."""
    router = Router()

    @router.query
    def f(
        name: Annotated[str, StringConstraints(min_length=3, max_length=9, pattern=r"^\w+$")],
    ) -> str:
        return ""

    out = generate_zod(router)
    assert r"name: z.string().min(3).max(9).regex(/^\w+$/)," in out


def test_optional_and_nullable() -> None:
    """`X | None` → `.nullable()`; `= None` default → `.optional()` on top."""
    router = Router()

    @router.query
    def f(a: str | None, b: str | None = None) -> str:
        return ""

    out = generate_zod(router)
    assert "a: z.string().nullable()," in out
    assert "b: z.string().nullable().optional()," in out


def test_literal_and_enum() -> None:
    """Literal members → z.literal union; str enum → z.enum."""
    router = Router()

    @router.query
    def f(kind: Literal["a", "b"], color: Color) -> str:
        return ""

    out = generate_zod(router)
    assert 'kind: z.union([z.literal("a"), z.literal("b")]),' in out
    assert 'color: z.enum(["red", "blue"]),' in out


def test_nested_model_const() -> None:
    """Nested Pydantic models become named consts referenced by inputs."""
    router = Router()

    @router.mutation
    def f(item: Inner) -> Inner:
        return item

    out = generate_zod(router)
    assert "export const Inner = z.object({\n  x: z.number().int().gte(0),\n});" in out
    assert "  item: Inner," in out


def test_discriminated_union() -> None:
    """Models sharing a Literal field emit `z.discriminatedUnion`."""
    router = Router()

    @router.mutation
    def f(pet: Cat | Dog) -> str:
        return ""

    out = generate_zod(router)
    assert 'pet: z.discriminatedUnion("kind", [Cat, Dog]),' in out


def test_plain_union() -> None:
    """Non-model unions emit `z.union`."""
    router = Router()

    @router.query
    def f(v: int | str) -> str:
        return ""

    assert "v: z.union([z.number().int(), z.string()])," in generate_zod(router)


def test_containers_and_records() -> None:
    """Lists → z.array, tuples → z.tuple, dicts → two-arg z.record."""
    router = Router()

    @router.query
    def f(xs: list[int], pair: tuple[str, int], m: dict[str, float]) -> str:
        return ""

    out = generate_zod(router)
    assert "xs: z.array(z.number().int())," in out
    assert "pair: z.tuple([z.string(), z.number().int()])," in out
    assert "m: z.record(z.string(), z.number())," in out


def test_temporal_and_uuid() -> None:
    """ISO-family annotations map to the zod v4 iso/uuid helpers."""
    router = Router()

    @router.query
    def f(at: datetime.datetime, day: datetime.date, uid: uuid.UUID) -> str:
        return ""

    out = generate_zod(router)
    assert "at: z.iso.datetime()," in out
    assert "day: z.iso.date()," in out
    assert "uid: z.uuid()," in out


def test_dropped_constraint_comment() -> None:
    """Unmappable metadata emits a `// dropped:` note, not a silent loss."""
    router = Router()

    @router.query
    def f(name: Annotated[str, StringConstraints(strip_whitespace=True)]) -> str:
        return ""

    out = generate_zod(router)
    assert "// dropped: StringConstraints.strip_whitespace" in out


def test_unannotated_parameter_rejected() -> None:
    """Unannotated params raise TypeError like the type generator."""
    router = Router()

    @router.query
    def f(x) -> str:  # type: ignore[no-untyped-def]
        return ""

    with pytest.raises(TypeError, match="unannotated"):
        generate_zod(router)


def test_serializer_metadata_rejected() -> None:
    """Serialization-changing Annotated metadata raises TypeError."""
    router = Router()

    @router.query
    def f(x: Annotated[int, PlainSerializer(str)]) -> str:
        return ""

    with pytest.raises(TypeError, match="serialization"):
        generate_zod(router)


def test_output_only_models_not_emitted() -> None:
    """Models reachable only through returns produce no schema consts."""

    class Out(BaseModel):
        x: int

    router = Router()

    @router.query
    def f() -> Out:
        return Out(x=1)

    out = generate_zod(router)
    assert "export const Out" not in out


def test_deterministic() -> None:
    """Repeated generation is byte-identical."""
    router = make_router()
    assert generate_zod(router) == generate_zod(router)


def test_js_regex_escapes_delimiter_only() -> None:
    """Only `/` is escaped; backslashes keep their regex meaning."""
    assert _js_regex(r"^a/b$") == r"/^a\/b$/"
    assert _js_regex(r"\d+") == r"/\d+/"


def test_zod_schemas_typecheck() -> None:
    """The emitted module parses as TS — verified by ts-tests typecheck too."""
    out = generate_zod(make_router())
    assert out.count("z.object({") >= 1
