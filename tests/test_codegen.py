def test_pydantic_alias_field_rejected() -> None:
    """A field whose serialization alias differs from its name is rejected.

    Runtime input validation of a nested model accepts the alias key and
    silently ignores (or rejects, when required) the Python field name, while
    output serialization emits the Python field name, so no single TypeScript
    property can describe both directions.
    """
    router = Router()

    @router.query
    def aliased(item: Aliased) -> Aliased:
        return item

    with pytest.raises(TypeError, match=r"model 'Aliased' field 'user_name'"):
        generate_types(router)
    with pytest.raises(TypeError, match="wire names differ"):
        generate_types(router)
    with pytest.raises(TypeError, match="accepts 'userName'"):
        generate_types(router)


