def test_string_safety() -> None:
    """Hostile strings in literals cannot inject TypeScript source."""
    hostile = '"); export type Injected = any; //'
    router = Router()
    namespace: dict[str, Any] = {"Literal": Literal, "hostile": hostile}
    exec(
        textwrap.dedent(
            """
            def hostile_literal(mode: Literal[hostile]) -> Literal[hostile]:
                return mode
            """
        ),
        namespace,
    )
    router.query(namespace["hostile_literal"])

    source = generate_types(router)
    # The literal is emitted as one JSON-escaped string token and never
    # terminates it, so no code can be injected outside the quotes.
    escaped = json.dumps(hostile)
    assert escaped in source
    assert "\nexport type Injected" not in source
    # With every emitted string token removed, no trace of the payload is left.
    assert "Injected" not in source.replace(escaped, "")


