def test_unsupported_annotations_fail_named() -> None:
    """Unsupported annotations raise TypeError naming procedure and annotation."""
    cases: list[tuple[str, str, str]] = [
        ("any_param", "x: Any", "Any"),
        ("object_param", "x: object", "object"),
        ("bytes_param", "x: bytes", "bytes"),
        ("bad_dict_keys", "x: dict[int, str]", "mapping keys must be strings"),
        ("bare_tuple", "x: tuple", "tuple"),
        ("custom_class", "x: _Custom", "_Custom"),
        ("unresolvable_str", "x: 'NotImportable'", "unsupported annotation"),
    ]
    for name, param, expected in cases:
        router = Router()
        namespace: dict[str, Any] = {"_Custom": type("_Custom", (), {}), "Any": Any}
        exec(
            textwrap.dedent(
                f"""
                def {name}({param}) -> int:
                    return 1
                """
            ),
            namespace,
        )
        router.query(namespace[name])
        with pytest.raises(TypeError, match=expected):
            generate_types(router)
        with pytest.raises(TypeError, match=f"procedure '{name}'"):
            generate_types(router)


