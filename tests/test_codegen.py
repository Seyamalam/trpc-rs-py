def _handler_for(model: type[BaseModel]) -> Callable[..., Any]:
    def handler(item):
        return item

    handler.__annotations__ = {"item": model, "return": model}
    return handler


def _runtime_contract(model: type[BaseModel]) -> tuple[frozenset[str], frozenset[str]]:
    """Probe the runtime input/output wire contract for a nested model.

    Uses the same machinery as `validation.py`: `build_input_validator` on a
    handler whose sole parameter/return is `model`, plus
    `build_output_validator` for the serialized output keys. Returns the
    accepted input keys and the emitted output keys.
    """
    validate = build_input_validator(_handler_for(model))
    dump = build_output_validator(_handler_for(model))
    assert validate is not None and dump is not None
    field_name = next(iter(model.model_fields))
    candidates = candidates_for(model)
    accepted = set()
    instance = None
    for key in sorted(candidates):
        try:
            _args, kwargs = validate({"item": {key: "a"}})
        except TRPCError:
            continue
        candidate = kwargs.get("item")
        # Pydantic's default extra="ignore" silently drops unknown keys when
        # the field has a default, so a key only counts as accepted when it
        # actually populated the field.
        if candidate is not None and getattr(candidate, field_name) == "a":
            accepted.add(key)
            instance = instance or candidate
    emitted = set(dump(instance).keys()) if instance is not None else set()
    return frozenset(accepted), frozenset(emitted)


def _assert_codegen_agreement(
    model: type[BaseModel],
    accepted: frozenset[str],
    emitted: frozenset[str],
) -> None:
    """Assert the generator agrees with the probed runtime contract.

    A single emitted output key that input also accepts becomes the generated
    property key; anything else must raise `TypeError` instead of emitting an
    inaccurate property.
    """
    router = Router()
    router.query(_handler_for(model))
    if len(emitted) == 1 and emitted <= accepted:
        source = generate_types(router)
        (key,) = sorted(emitted)
        pattern = rf"  {re.escape(key)}\??: string;"
        assert re.search(pattern, source), model.__name__
        for other in sorted(candidates_for(model) - {key}):
            other_pattern = rf"  {re.escape(other)}\??: string;"
            assert not re.search(other_pattern, source), model.__name__
    else:
        with pytest.raises(TypeError):
            generate_types(router)


def candidates_for(model: type[BaseModel]) -> set[str]:
    ((field_name, info),) = model.model_fields.items()
    names = {field_name}
    for alias in (info.alias, info.validation_alias, info.serialization_alias):
        if isinstance(alias, str):
            names.add(alias)
    return names


def test_pydantic_alias_config_matrix_runtime_and_codegen_agree() -> None:
    """Runtime input/output keys and the generator agree for every config.

    Each case first probes the installed Pydantic runtime (which keys input
    validation accepts, which key serialization emits) and then asserts the
    generator emits exactly that single key — or raises `TypeError` when the
    two directions cannot share one property.
    """
    cases: list[type[BaseModel]] = [
        Aliased,
        AliasedByName,
        AliasedPopulateByName,
        ValidateByNameOnly,
        ValidateByAliasDisabled,
        ValidateByAliasOnly,
        NameInputAliasOutput,
        SerializeByAliasMismatch,
        PopulateAndSerializeMismatch,
        SerializeSeparateAliases,
        SerializeByAliasSymmetric,
    ]
    expected: dict[str, tuple[frozenset[str], frozenset[str]]] = {
        "Aliased": (frozenset({"userName"}), frozenset({"user_name"})),
        "AliasedByName": (frozenset({"user_name"}), frozenset({"user_name"})),
        "AliasedPopulateByName": (
            frozenset({"user_name", "userName"}),
            frozenset({"user_name"}),
        ),
        "ValidateByNameOnly": (
            frozenset({"value", "wireValue"}),
            frozenset({"value"}),
        ),
        "ValidateByAliasDisabled": (frozenset({"value"}), frozenset({"value"})),
        "ValidateByAliasOnly": (frozenset({"wireValue"}), frozenset({"value"})),
        "NameInputAliasOutput": (frozenset({"value"}), frozenset({"wireValue"})),
        "SerializeByAliasMismatch": (frozenset({"value"}), frozenset({"wireValue"})),
        "PopulateAndSerializeMismatch": (
            frozenset({"value"}),
            frozenset({"wireValue"}),
        ),
        "SerializeSeparateAliases": (frozenset({"aliasKey"}), frozenset({"outKey"})),
        "SerializeByAliasSymmetric": (
            frozenset({"wireValue"}),
            frozenset({"wireValue"}),
        ),
    }
    for model in cases:
        accepted, emitted = _runtime_contract(model)
        assert accepted == expected[model.__name__][0], model.__name__
        assert emitted == expected[model.__name__][1], model.__name__
        _assert_codegen_agreement(model, accepted, emitted)


