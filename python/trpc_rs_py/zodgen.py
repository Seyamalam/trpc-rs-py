"""Zod schema generation from a :class:`Router`.

`trpc-py codegen zod` emits a TypeScript module of `zod` schemas covering
procedure inputs, so frontend forms validate with the same rules as the
Pydantic-backed handlers. Constraint mapping follows
`docs/codegen.md` ("Zod schemas"): lengths, regex, numeric ranges, enums,
literals, optional/nullable fields, unions, and discriminated unions map to
their Zod counterparts; constraints with no Zod equivalent are emitted as
`// dropped:` comments rather than silently lost. Anything whose *shape*
cannot be represented (custom serializers, computed fields, `RootModel`,
unannotated parameters, `**kwargs`) raises `TypeError` — the same refusal
set as `codegen.generate_types`, enforced by sharing `_Generator`'s checks.

The emitted module targets `zod` v4 (`z.iso.datetime()`, two-argument
`z.record`, `z.discriminatedUnion`).
"""

from __future__ import annotations

# Imports codegen/router internals deliberately: the traversal and the
# refusal set must not drift from generate_types.
# pyright: reportPrivateUsage=false
import datetime
import inspect
import json
import uuid
from collections.abc import Callable
from enum import Enum
from types import NoneType, UnionType
from typing import Annotated, Any, Literal, Union, get_args, get_origin

from annotated_types import Ge, Gt, Interval, Le, Lt, MaxLen, MinLen, MultipleOf
from pydantic import BaseModel, RootModel
from pydantic.fields import FieldInfo
from pydantic.types import StringConstraints

from .codegen import (
    _DICT_LIKE,
    _LIST_LIKE,
    _MISSING,
    _SET_LIKE,
    _STRING_TYPES,
    _build_tree,
    _flatten,
    _Generator,
    _is_one_of,
    _limit,
    _ts_identifier,
    _ts_key,
    _ts_literal,
)
from .router import ProcedureKind, Router, _signature_of, type_hints_of

__all__ = ["generate_zod"]

_HEADER = """\
// Generated by `trpc-py codegen zod` from the Python router. Do not edit.
// Pydantic constraints with no Zod equivalent are marked `// dropped:` —
// see docs/codegen.md ("Zod schemas") for the full mapping table.
import { z } from "zod";
"""


def _js_regex(pattern: str) -> str:
    r"""Render a Python regex source as a JavaScript `/.../ ` literal.

    Only the `/` delimiter is escaped; backslashes are regex tokens with the
    same meaning in both engines. Python-only constructs (`\A`, `\Z`, named
    groups `(?P<…>)`) are a documented drop risk.

    Example:
        ```python
        from trpc_rs_py.zodgen import _js_regex

        assert _js_regex(r"^\w+/\d$") == "/^\\w+\\/\\d$/"
        ```
    """
    return "/" + pattern.replace("/", "\\/") + "/"


def _num(value: object) -> str:
    """Render a numeric bound without a trailing `.0` for ints.

    Example:
        ```python
        from trpc_rs_py.zodgen import _num

        assert _num(3.0) == "3"
        ```
    """
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return repr(value)


class _ZodGenerator(_Generator):
    """Map annotations to `zod` schema expressions, collecting model consts.

    Inherits unique naming plus every shape/serialization refusal from
    `_Generator`; `map_zod` mirrors `map_annotation`'s traversal.
    """

    def map_zod(self, annotation: object, where: str, dropped: list[str]) -> str:
        """Map a Python annotation to a zod expression string.

        Args:
            annotation: The resolved annotation object.
            where: Human-readable location used in error messages.
            dropped: Accumulator for `// dropped:` constraint notes.

        Returns:
            A zod expression such as `"z.array(z.string())"`.

        Raises:
            TypeError: For annotations `generate_types` also cannot
                represent.
        """
        annotation_repr = repr(annotation)
        origin = get_origin(annotation)
        if origin is Annotated:
            args = get_args(annotation)
            self._check_annotated_metadata(args[1:], where)
            inner = self.map_zod(args[0], where, dropped)
            return self._apply_constraints(inner, args[1:], where, dropped)
        if annotation is None or annotation is NoneType:
            return "z.null()"
        if origin is Union or origin is UnionType:
            return self._map_union(get_args(annotation), where, dropped)
        if annotation is bool:
            return "z.boolean()"
        if annotation is int:
            return "z.number().int()"
        if annotation is float:
            return "z.number()"
        if annotation is str:
            return "z.string()"
        if annotation is datetime.datetime:
            return "z.iso.datetime()"
        if annotation is datetime.date:
            return "z.iso.date()"
        if annotation is datetime.time:
            return "z.iso.time()"
        if annotation is datetime.timedelta:
            return "z.iso.duration()"
        if annotation is uuid.UUID:
            return "z.uuid()"
        if _is_one_of(annotation, _LIST_LIKE) or _is_one_of(annotation, _SET_LIKE):
            return "z.array(z.unknown())"
        if _is_one_of(annotation, _DICT_LIKE):
            return "z.record(z.string(), z.unknown())"
        if _is_one_of(annotation, _STRING_TYPES):
            return "z.string()"
        args = get_args(annotation)
        if origin is Literal:
            if not args:
                msg = f"{where}: empty Literal"
                raise TypeError(msg)
            tokens = [f"z.literal({_ts_literal(v, where)})" for v in args]
            unique = list(dict.fromkeys(tokens))
            return unique[0] if len(unique) == 1 else f"z.union([{', '.join(unique)}])"
        if origin in _LIST_LIKE or origin in _SET_LIKE:
            if len(args) != 1:
                msg = f"{where}: unsupported container annotation {_limit(repr(annotation))}"
                raise TypeError(msg)
            return f"z.array({self.map_zod(args[0], where, dropped)})"
        if origin is tuple:
            if not args or args == (Ellipsis,):
                msg = f"{where}: unsupported tuple annotation {_limit(repr(annotation))}"
                raise TypeError(msg)
            if args[-1] is Ellipsis:
                if len(args) != 2:
                    msg = f"{where}: unsupported tuple annotation {_limit(repr(annotation))}"
                    raise TypeError(msg)
                return f"z.array({self.map_zod(args[0], where, dropped)})"
            inner = ", ".join(self.map_zod(a, where, dropped) for a in args)
            return f"z.tuple([{inner}])"
        if origin in _DICT_LIKE:
            if len(args) != 2:
                msg = f"{where}: unsupported mapping annotation {_limit(repr(annotation))}"
                raise TypeError(msg)
            if self.map_annotation(args[0], where) != "string":
                msg = f"{where}: mapping keys must be strings for JSON objects"
                raise TypeError(msg)
            return f"z.record(z.string(), {self.map_zod(args[1], where, dropped)})"
        if isinstance(annotation, type) and issubclass(annotation, Enum):
            values = [m.value for m in annotation.__members__.values()]
            if not values:
                msg = f"{where}: enum {annotation.__name__!r} has no members"
                raise TypeError(msg)
            if all(isinstance(v, str) for v in values):
                names = ", ".join(f'"{v}"' for v in values)
                return f"z.enum([{names}])"
            members = ", ".join(f"z.literal({_ts_literal(v, where)})" for v in values)
            return f"z.union([{members}])"
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            if issubclass(annotation, RootModel):
                msg = (
                    f"{where}: RootModel subclasses validate a bare scalar or "
                    "array, not an object schema; annotate the root type directly"
                )
                raise TypeError(msg)
            return self._register_zod_model(annotation, where)
        msg = (
            f"{where}: unsupported annotation {_limit(annotation_repr)}; "
            "no Zod schema can validate it exactly"
        )
        raise TypeError(msg)

    def _map_union(self, members: tuple[object, ...], where: str, dropped: list[str]) -> str:
        """Map a union annotation to its zod expression.

        `Optional` members emit `.nullable()`; model unions sharing a
        `Literal` field emit `z.discriminatedUnion`; others emit `z.union`.

        Args:
            members: The union's member annotations.
            where: Location text for error messages.
            dropped: `// dropped:` accumulator.

        Returns:
            The union expression.
        """
        non_null = [m for m in members if m is not NoneType]
        nullable = len(non_null) != len(members)
        discriminator = _find_discriminator(non_null)
        mapped = ", ".join(self.map_zod(m, where, dropped) for m in non_null)
        if not non_null:
            msg = f"{where}: union of only None"
            raise TypeError(msg)
        if len(non_null) == 1:
            out = mapped
        elif discriminator is not None:
            out = f'z.discriminatedUnion("{discriminator}", [{mapped}])'
        else:
            out = f"z.union([{mapped}])"
        return out + ".nullable()" if nullable else out

    def _apply_constraints(
        self,
        inner: str,
        metadata: tuple[object, ...],
        where: str,
        dropped: list[str],
    ) -> str:
        """Attach `.gt/.min/.regex/...` calls for mappable constraint metadata.

        Args:
            inner: The mapped base expression.
            metadata: `Annotated` extras or `FieldInfo.metadata` entries.
            where: Location text for error messages.
            dropped: `// dropped:` accumulator.

        Returns:
            The expression with constraint methods appended.
        """
        out = inner
        for item in metadata:
            if isinstance(item, FieldInfo):
                out = self._apply_constraints(out, tuple(item.metadata), where, dropped)
            elif isinstance(item, Gt):
                out += f".gt({_num(item.gt)})"
            elif isinstance(item, Ge):
                out += f".gte({_num(item.ge)})"
            elif isinstance(item, Lt):
                out += f".lt({_num(item.lt)})"
            elif isinstance(item, Le):
                out += f".lte({_num(item.le)})"
            elif isinstance(item, MultipleOf):
                out += f".multipleOf({_num(item.multiple_of)})"
            elif isinstance(item, MinLen):
                out += f".min({item.min_length})"
            elif isinstance(item, MaxLen):
                out += f".max({item.max_length})"
            elif isinstance(item, Interval):
                if item.gt is not None:
                    out += f".gt({_num(item.gt)})"
                if item.ge is not None:
                    out += f".gte({_num(item.ge)})"
                if item.lt is not None:
                    out += f".lt({_num(item.lt)})"
                if item.le is not None:
                    out += f".lte({_num(item.le)})"
            elif isinstance(item, StringConstraints):
                out = self._apply_string_constraints(out, item, dropped)
            elif type(item).__module__.startswith("pydantic"):
                continue  # Pydantic-internal metadata, not a constraint.
            else:
                dropped.append(type(item).__name__)
        return out

    def _apply_string_constraints(
        self, inner: str, item: StringConstraints, dropped: list[str]
    ) -> str:
        """Map `StringConstraints` members to zod string methods."""
        out = inner
        if item.min_length is not None:
            out += f".min({item.min_length})"
        if item.max_length is not None:
            out += f".max({item.max_length})"
        if item.pattern is not None:
            source = item.pattern if isinstance(item.pattern, str) else item.pattern.pattern
            out += f".regex({_js_regex(source)})"
        for name in ("to_lower", "to_upper", "strip_whitespace", "strict"):
            if getattr(item, name, None):
                dropped.append(f"StringConstraints.{name}")
        return out

    def _register_zod_model(self, model: type[BaseModel], where: str) -> str:
        """Register a model schema const, mapping its fields recursively."""
        existing = self._model_names.get(id(model))
        if existing is not None:
            return existing
        name = self.unique_name(model.__name__)
        self._model_names[id(model)] = name
        self._check_model_shape(model)
        lines: list[str] = []
        for field_name, info in model.model_fields.items():
            annotation = info.annotation
            if annotation is None:
                msg = f"model {model.__name__!r} field {field_name!r}: untyped field"
                raise TypeError(msg)
            field_where = f"model {model.__name__!r} field {field_name!r}"
            self._check_field_serialization(model, field_name, info, field_where)
            key = self._field_wire_name(model, field_name, info, field_where)
            dropped: list[str] = []
            expr = self.map_zod(annotation, field_where, dropped)
            expr = self._apply_constraints(expr, tuple(info.metadata), field_where, dropped)
            expr = self._wrap_default(expr, info, dropped)
            for note in dict.fromkeys(dropped):
                lines.append(f"  // dropped: {note}")
            lines.append(f"  {_ts_key(key)}: {expr},")
        self._model_bodies.append((name, lines))
        return name

    def _wrap_default(self, expr: str, info: FieldInfo, dropped: list[str]) -> str:
        """Map a field's optionality/default to `.optional/.default/.nullish`."""
        if info.is_required():
            return expr
        if info.default is None and info.default_factory is None:
            suffix = ".optional()" if expr.endswith(".nullable()") else ".nullish()"
            return expr + suffix
        if info.default_factory is not None:
            dropped.append("default_factory")
            return f"{expr}.optional()"
        if isinstance(info.default, BaseModel):
            dropped.append("model default value")
            return f"{expr}.optional()"
        try:
            literal = _ts_literal(info.default, "field default")
        except TypeError:
            try:
                literal = json.dumps(info.default, separators=(",", ":"))
            except (TypeError, ValueError):
                dropped.append("non-JSON default value")
                return f"{expr}.optional()"
        return f"{expr}.default({literal})"


def _find_discriminator(members: list[object]) -> str | None:
    """Return a shared `Literal` field name usable as a union discriminator.

    Every member must be a `BaseModel` subclass carrying a `Literal[...]`
    field with the same name; returns `None` otherwise.
    """
    candidates: set[str] | None = None
    for member in members:
        if not (isinstance(member, type) and issubclass(member, BaseModel)):
            return None
        literal_fields = {
            name
            for name, info in member.model_fields.items()
            if info.annotation is not None and get_origin(info.annotation) is Literal
        }
        if not literal_fields:
            return None
        candidates = literal_fields if candidates is None else candidates & literal_fields
        if not candidates:
            return None
    return None if candidates is None else sorted(candidates)[0]


def _input_schema(
    generator: _ZodGenerator,
    path: str,
    kind: ProcedureKind,
    handler: Callable[..., Any],
    hints: dict[str, Any],
) -> list[str] | None:
    """Derive `z.object` member lines for one procedure's input.

    Follows the same parameter contract as codegen's `_input_members`:
    annotated ordinary parameters become object properties; `lastEventId` on
    subscriptions is protocol metadata, not input; unannotated parameters,
    `**kwargs`, and `*args`-only handlers raise `TypeError`.

    Returns:
        Member lines for `z.object({...})`, or `None` for no-input
        procedures.
    """
    signature = _signature_of(handler)
    if signature is None:
        msg = f"procedure {path!r}: cannot inspect the handler's signature"
        raise TypeError(msg)
    ordinary: list[inspect.Parameter] = []
    for index, parameter in enumerate(signature.parameters.values()):
        if parameter.kind is inspect.Parameter.VAR_KEYWORD:
            msg = f"procedure {path!r}: **kwargs cannot be expressed as a zod schema"
            raise TypeError(msg)
        if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
            if not ordinary:
                msg = f"procedure {path!r}: *args-only handlers cannot be expressed"
                raise TypeError(msg)
            continue
        if index == 0 and parameter.name == "ctx":
            # Injected request context, not client input (trpc_rs_py.context).
            continue
        if kind is ProcedureKind.SUBSCRIPTION and parameter.name == "lastEventId":
            continue
        ordinary.append(parameter)
    if not ordinary:
        return None
    lines: list[str] = []
    for parameter in ordinary:
        annotation = hints.get(parameter.name, _MISSING)
        if annotation is _MISSING or annotation is inspect.Parameter.empty:
            msg = f"procedure {path!r}: parameter {parameter.name!r} is unannotated"
            raise TypeError(msg)
        where = f"procedure {path!r} parameter {parameter.name!r}"
        dropped: list[str] = []
        expr = generator.map_zod(annotation, where, dropped)
        if parameter.default is not inspect.Parameter.empty:
            if parameter.default is None:
                expr += ".optional()" if expr.endswith(".nullable()") else ".nullish()"
            else:
                expr += f".default({_ts_literal(parameter.default, where)})"
        for note in dict.fromkeys(dropped):
            lines.append(f"  // dropped: {note}")
        lines.append(f"  {_ts_key(parameter.name)}: {expr},")
    return lines


def _const_name(path: str) -> str:
    """Turn a procedure path into a `<Pascal>Input` const base name.

    Example:
        ```python
        from trpc_rs_py.zodgen import _const_name

        assert _const_name("posts.by_id") == "Posts_by_idInput"
        ```
    """
    base = _ts_identifier(path.replace(".", "_").replace("-", "_"))
    return base[:1].upper() + base[1:] + "Input"


def generate_zod(router: Router) -> str:
    """Emit a TypeScript module of zod v4 schemas for procedure inputs.

    The output contains one `export const <Model>` per referenced Pydantic
    model plus one `export const <Proc>Input` per procedure that takes
    input, in deterministic order, with `// dropped:` comments wherever a
    Pydantic constraint has no Zod equivalent.

    Args:
        router: The router whose annotated handlers to describe.

    Returns:
        TypeScript module text (trailing newline included).

    Raises:
        TypeError: If any input annotation has no exact Zod mapping — the
            same refusal set as `generate_types`.

    Example:
        ```python
        from trpc_rs_py import Router
        from trpc_rs_py.zodgen import generate_zod

        router = Router()

        @router.query
        def greet(name: str) -> str:
            return name

        assert "export const GreetInput = z.object({" in generate_zod(router)
        ```
    """
    generator = _ZodGenerator()
    inputs: list[tuple[str, list[str] | None]] = []
    for path, procedure in _flatten(_build_tree(router)):
        hints = type_hints_of(procedure.handler)
        lines = _input_schema(generator, path, procedure.kind, procedure.handler, hints)
        inputs.append((path, lines))
    chunks = [_HEADER]
    for name, lines in generator.model_sources:
        body = "\n".join(lines)
        chunks.append(f"export const {name} = z.object({{\n{body}\n}});\n")
    for path, lines in inputs:
        name = generator.unique_name(_const_name(path))
        if lines is None:
            chunks.append(f"// procedure {path!r} takes no input\n")
            continue
        body = "\n".join(lines)
        chunks.append(f"export const {name} = z.object({{\n{body}\n}});\n")
    return "".join(chunks)
