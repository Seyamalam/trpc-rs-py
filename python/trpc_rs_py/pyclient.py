"""Python client stub generation from a `Router` (ADR 0014).

`trpc-py codegen py-client` emits a self-contained Python module defining
`AppRouterClient`: a thin typed wrapper over `trpc_rs_py.client.Client` with
one method per procedure. Because the stub is Python, the handler's own
parameter and return annotations are copied verbatim — no type translation,
no `any`. Each method packs its arguments into the procedure's input object
and delegates to `client.query`/`mutation`/`subscribe`, so the generated
file can be checked into a service repo and type-checked with mypy
directly.

Example:
    ```python
    from trpc_rs_py import Router
    from trpc_rs_py.pyclient import generate_python_client

    router = Router()

    @router.query
    def greeting(name: str) -> str:
        return f"Hello {name}!"

    source = generate_python_client(router)
    assert "def greeting(self, name: str) -> str:" in source
    ```
"""

from __future__ import annotations

# Imports codegen/router internals deliberately: path handling and
# signature/annotation resolution must not drift from generate_types.
# pyright: reportPrivateUsage=false
import ast
import inspect
import json
import keyword
import math
import re
from enum import Enum
from types import NoneType, UnionType
from typing import Annotated, Any, Literal, Union, cast, get_args, get_origin

from .codegen import _build_tree, _flatten
from .router import (
    Procedure,
    ProcedureKind,
    Router,
    _signature_of,
    type_hints_of,
)

__all__ = ["generate_python_client"]

_ILLEGAL_IDENT_CHARS = re.compile(r"[^A-Za-z0-9_]")
_LEADING_IDENT_CHAR = re.compile(r"[A-Za-z_]")
_DUNDER_SHAPED = re.compile(r"__.*__\Z")

# Names the generated class uses for itself; a procedure mapping to one of
# them would collide with the wrapper's own machinery.
_RESERVED_METHODS = frozenset({"__init__", "_client"})

_HEADER = """\
# Generated by `trpc-py codegen py-client` from the Python router. Do not edit.
# Regenerate with `generate_python_client(router)` or `trpc-py codegen py-client`."""


def _py_identifier(name: str) -> str:
    """Reduce a procedure path to a safe Python method-name fragment.

    Path characters outside `[A-Za-z0-9_]` (dots, dashes) become `_`; a
    leading digit is prefixed with `_`; keywords get the idiomatic trailing
    underscore (`class` → `class_`); dunder-shaped names and names colliding
    with the wrapper's own members are prefixed `call_` so they can never
    hijack the class protocol (`__eq__` stays `__eq__`-free).

    Args:
        name: A procedure path, e.g. `posts.by_id`.

    Returns:
        A valid Python identifier safe as a method name.

    Example:
        ```python
        from trpc_rs_py.pyclient import _py_identifier

        assert _py_identifier("posts.by_id") == "posts_by_id"
        assert _py_identifier("9lives") == "_9lives"
        assert _py_identifier("class") == "class_"
        ```
    """
    cleaned = _ILLEGAL_IDENT_CHARS.sub("_", name)
    if not cleaned or not _LEADING_IDENT_CHAR.match(cleaned[0]):
        cleaned = f"_{cleaned}"
    if keyword.iskeyword(cleaned):
        return f"{cleaned}_"
    if _DUNDER_SHAPED.fullmatch(cleaned) or cleaned in _RESERVED_METHODS:
        return f"call_{cleaned}"
    return cleaned


class _Imports:
    """Collect the import statements a generated module needs."""

    def __init__(self) -> None:
        """Start empty; `trpc_rs_py.client` names are added at render."""
        self.typing_names: set[str] = set()
        self.abc_names: set[str] = set()
        self.modules: set[str] = set()

    def render(self, *, has_subscriptions: bool) -> list[str]:
        """Return the import block lines in deterministic order."""
        if has_subscriptions:
            self.abc_names.add("Iterator")
        lines = ["from __future__ import annotations", ""]
        if self.abc_names:
            lines.append(f"from collections.abc import {', '.join(sorted(self.abc_names))}")
        if self.typing_names:
            lines.append(f"from typing import {', '.join(sorted(self.typing_names))}")
        for module in sorted(self.modules):
            lines.append(f"import {module}")
        names = "Client, SubscriptionEvent" if has_subscriptions else "Client"
        lines.append(f"from trpc_rs_py.client import {names}")
        return lines


def _strs(parts: list[str | None]) -> list[str]:
    """Narrow `str | None` tokens to `str` after an `all(...)` guard."""
    return [part for part in parts if part is not None]


def _literal_source(value: object, imports: _Imports) -> str | None:
    """Render a `Literal[...]` member or parameter default as source text.

    Scalars render via `repr` (strings quote cleanly); enum members render
    as `module.Qual.NAME`; containers are accepted only when
    `ast.literal_eval` round-trips the `repr`, which keeps `nan`/`inf` and
    arbitrary objects out of the emitted source. Returns `None` when the
    value cannot be rendered — callers decide whether that is fatal.
    """
    if value is None or isinstance(value, (bool, int, str, bytes)):
        return repr(value)
    if isinstance(value, float):
        return repr(value) if math.isfinite(value) else None
    if value is Ellipsis:
        return "..."
    if isinstance(value, Enum):
        qualname = type(value).__qualname__
        if "<locals>" in qualname:
            return None
        imports.modules.add(type(value).__module__)
        return f"{type(value).__module__}.{qualname}.{value.name}"
    if isinstance(value, (tuple, list, dict, set, frozenset)):
        text = repr(cast(object, value))
        try:
            return text if ast.literal_eval(text) == value else None
        except (ValueError, SyntaxError, TypeError, MemoryError, RecursionError):
            return None
    return None


def _render_object(annotation: object, imports: _Imports) -> str | None:
    """Render a non-generic object (a class or ABC) as `module.Qual`."""
    if not isinstance(annotation, type):
        return None
    module = annotation.__module__
    qualname = annotation.__qualname__
    if "<locals>" in qualname:
        return None
    if module == "builtins":
        return qualname
    if module == "typing":
        imports.typing_names.add(qualname)
        return qualname
    if module == "collections.abc":
        imports.abc_names.add(qualname)
        return qualname
    imports.modules.add(module)
    return f"{module}.{qualname}"


def _annotation_source(
    annotation: object,
    imports: _Imports,
    *,
    depth: int = 0,
) -> str | None:
    """Render a resolved type-hint object as Python source text.

    Mirrors the resolved annotation as closely as a stub needs: `Annotated`
    metadata (server-side validation constraints) is unwrapped to the base
    type; unions render as `X | Y`; parametrized generics render as
    `Origin[args]`; `Literal` members render through `_literal_source`;
    unresolved string annotations pass through as quoted literals. Anything
    else — TypeVars, locally-defined classes, opaque objects — returns
    `None` so the caller can omit the annotation rather than emit wrong
    source.
    """
    if depth > 32:
        return None
    if annotation is inspect.Parameter.empty or annotation is inspect.Signature.empty:
        return None
    if annotation is None or annotation is NoneType:
        return "None"
    if annotation is Any:
        imports.typing_names.add("Any")
        return "Any"
    if isinstance(annotation, str):
        return repr(annotation)
    origin = get_origin(annotation)
    if origin is Annotated:
        args = get_args(annotation)
        return _annotation_source(args[0], imports, depth=depth + 1)
    if origin is Union or origin is UnionType:
        parts = [_annotation_source(arg, imports, depth=depth + 1) for arg in get_args(annotation)]
        return " | ".join(_strs(parts)) if all(part is not None for part in parts) else None
    if origin is Literal:
        members = [_literal_source(arg, imports) for arg in get_args(annotation)]
        if not all(member is not None for member in members):
            return None
        imports.typing_names.add("Literal")
        return f"Literal[{', '.join(_strs(members))}]"
    if origin is not None:
        rendered_origin = _render_object(origin, imports)
        if rendered_origin is None:
            return None
        args = get_args(annotation)
        tokens: list[str] = []
        for arg in args:
            if arg is Ellipsis:
                tokens.append("...")
                continue
            if isinstance(arg, list):
                # `Callable[[A, B], R]` carries its parameters as a list.
                inner = [
                    _annotation_source(item, imports, depth=depth + 1)
                    for item in cast("list[object]", arg)
                ]
                if not all(item is not None for item in inner):
                    return None
                tokens.append(f"[{', '.join(_strs(inner))}]")
                continue
            rendered = _annotation_source(arg, imports, depth=depth + 1)
            if rendered is None:
                return None
            tokens.append(rendered)
        return f"{rendered_origin}[{', '.join(tokens)}]"
    return _render_object(annotation, imports)


def _default_source(value: object, imports: _Imports, where: str) -> str:
    """Render a parameter default value as source text.

    Raises:
        TypeError: The default cannot be rendered — naming the procedure
            and parameter via `where`.
    """
    rendered = _literal_source(value, imports)
    if rendered is None:
        msg = f"{where}: cannot render default value {value!r} in a client stub"
        raise TypeError(msg)
    return rendered


def _unique_arg_name(name: str, used: set[str]) -> str:
    """Rename a parameter colliding with `self` by appending underscores."""
    candidate = name
    while candidate in used:
        candidate = f"{candidate}_"
    used.add(candidate)
    return candidate


def _method_parameters(
    path: str,
    kind: ProcedureKind,
    procedure: Procedure,
    hints: dict[str, Any],
    imports: _Imports,
) -> tuple[list[str], str]:
    """Build the stub's parameter list and input-packing expression.

    Returns `(signature_parts, input_expr)` where `signature_parts` follow
    `self` in declaration order (`/`, `*`, `*args`, `**kwargs` markers
    included) and `input_expr` is the second argument to the client call —
    the JSON input object, a list for `*args`-only handlers, or `""` when
    the procedure takes no input.

    Mirrors the runtime input contract (`validation.py`): a leading `ctx`
    parameter is injected context, never client input, and a subscription's
    `lastEventId` parameter is resume metadata the adapter injects.
    """
    signature = _signature_of(procedure.handler)
    if signature is None:
        msg = (
            f"procedure {path!r}: cannot inspect the handler's signature; "
            "py-client codegen requires an introspectable function"
        )
        raise TypeError(msg)
    parameters = list(signature.parameters.values())
    if parameters and parameters[0].name == "ctx":
        # Injected request context, not client input (trpc_rs_py.context).
        parameters = parameters[1:]
    ordinary: list[inspect.Parameter] = []
    var_positional: inspect.Parameter | None = None
    var_keyword: inspect.Parameter | None = None
    for parameter in parameters:
        if kind is ProcedureKind.SUBSCRIPTION and parameter.name == "lastEventId":
            # Protocol resume metadata injected by the adapter.
            continue
        if parameter.kind is inspect.Parameter.VAR_POSITIONAL:
            var_positional = parameter
        elif parameter.kind is inspect.Parameter.VAR_KEYWORD:
            var_keyword = parameter
        else:
            ordinary.append(parameter)
    if var_positional is not None and (ordinary or var_keyword is not None):
        msg = (
            f"procedure {path!r}: a handler mixing *args with named or "
            "**kwargs parameters has no wire input shape; declare explicit "
            "parameters instead"
        )
        raise TypeError(msg)

    used_arg_names: set[str] = {"self"}
    keys: list[tuple[str, str]] = []
    if var_positional is not None:
        stub_name = _unique_arg_name(var_positional.name, used_arg_names)
        return [f"*{stub_name}"], f"list({stub_name})"

    parts: list[str] = []
    positional_only = 0
    keyword_only_started = False
    for parameter in ordinary:
        stub_name = _unique_arg_name(parameter.name, used_arg_names)
        rendered = stub_name
        annotation = _annotation_source(hints.get(parameter.name, inspect.Parameter.empty), imports)
        if annotation is not None:
            rendered += f": {annotation}"
        if parameter.default is not inspect.Parameter.empty:
            where = f"procedure {path!r} parameter {parameter.name!r}"
            rendered += f" = {_default_source(parameter.default, imports, where)}"
        if parameter.kind is inspect.Parameter.POSITIONAL_ONLY:
            parts.append(rendered)
            positional_only += 1
        else:
            if parameter.kind is inspect.Parameter.KEYWORD_ONLY and not keyword_only_started:
                parts.append("*")
                keyword_only_started = True
            parts.append(rendered)
        keys.append((parameter.name, stub_name))
    if positional_only:
        parts.insert(positional_only, "/")
    if var_keyword is not None:
        stub_name = _unique_arg_name(var_keyword.name, used_arg_names)
        parts.append(f"**{stub_name}")
        if keys:
            packed = ", ".join(f"{json.dumps(key)}: {stub}" for key, stub in keys)
            return parts, f"{{{packed}, **{stub_name}}}"
        return parts, stub_name
    if not keys:
        return parts, ""
    packed = ", ".join(f"{json.dumps(key)}: {stub}" for key, stub in keys)
    return parts, f"{{{packed}}}"


def _unique_method_name(path: str, used: set[str]) -> str:
    """Assign a collision-free method name for a procedure path."""
    base = _py_identifier(path)
    name = base
    counter = 2
    while name in used:
        name = f"{base}_{counter}"
        counter += 1
    used.add(name)
    return name


def _emit_method(
    path: str,
    procedure: Procedure,
    method_name: str,
    imports: _Imports,
) -> list[str]:
    """Emit one stub method for a procedure.

    Queries delegate to `client.query`, mutations to `client.mutation`,
    subscriptions to `client.subscribe` (returning the
    `Iterator[SubscriptionEvent]` the base client produces).
    """
    hints = type_hints_of(procedure.handler)
    parts, input_expr = _method_parameters(path, procedure.kind, procedure, hints, imports)
    client_method = {
        ProcedureKind.QUERY: "query",
        ProcedureKind.MUTATION: "mutation",
        ProcedureKind.SUBSCRIPTION: "subscribe",
    }[procedure.kind]
    call_args = f"{json.dumps(path)}"
    if input_expr:
        call_args += f", {input_expr}"
    call = f"self._client.{client_method}({call_args})"
    if procedure.kind is ProcedureKind.SUBSCRIPTION:
        returns = "Iterator[SubscriptionEvent]"
        body = f"return {call}"
    else:
        rendered = _annotation_source(hints.get("return", inspect.Signature.empty), imports)
        if rendered:
            # The client returns `Any` off the wire; the stub asserts the
            # declared schema so callers keep end-to-end types under strict.
            imports.typing_names.add("cast")
            body = f"return cast({rendered}, {call})"
            returns = rendered
        else:
            body = f"return {call}"
            returns = ""
    signature = ", ".join(["self", *parts])
    returns_text = f" -> {returns}" if returns else ""
    return [
        f"    def {method_name}({signature}){returns_text}:",
        f'        """Call the `{path}` {procedure.kind.value} procedure."""',
        f"        {body}",
    ]


def generate_python_client(router: Router) -> str:
    """Emit a Python module defining `AppRouterClient` for `router`.

    The generated class wraps `trpc_rs_py.client.Client`: one method per
    procedure, parameter and return annotations copied verbatim from the
    handlers (leading `ctx` and subscription `lastEventId` parameters
    excluded — they are injected, not input), each body a one-line
    delegation packing the arguments into the wire input. Output is
    deterministic: procedure order follows router registration order (the
    same DFS order `generate_types` uses).

    Args:
        router: The router whose procedures are generated.

    Returns:
        Python module source, ready to write to a `.py` file (trailing
        newline included).

    Raises:
        TypeError: If a handler's signature cannot be inspected, mixes
            `*args` with named parameters, or carries an unrenderable
            default — always naming the procedure.

    Example:
        ```python
        from trpc_rs_py import Router
        from trpc_rs_py.pyclient import generate_python_client

        router = Router()

        @router.query
        def health() -> bool:
            return True

        source = generate_python_client(router)
        assert "def health(self) -> bool:" in source
        ```
    """
    flat = _flatten(_build_tree(router))
    imports = _Imports()
    used_names: set[str] = set(_RESERVED_METHODS)
    method_blocks: list[list[str]] = []
    has_subscriptions = False
    for path, procedure in flat:
        has_subscriptions = has_subscriptions or procedure.kind is ProcedureKind.SUBSCRIPTION
        method_name = _unique_method_name(path, used_names)
        method_blocks.append(_emit_method(path, procedure, method_name, imports))

    lines = [_HEADER, ""]
    lines.extend(imports.render(has_subscriptions=has_subscriptions))
    lines.append("")
    lines.append("")
    lines.append("class AppRouterClient:")
    lines.append('    """Typed stub over `Client` for the AppRouter procedures.')
    lines.append("")
    lines.append("    Each method packs its parameters into the procedure's input")
    lines.append("    object and delegates to `query`/`mutation`/`subscribe`.")
    lines.append('    """')
    lines.append("")
    lines.append("    def __init__(self, client: Client) -> None:")
    lines.append('        """Store the base client every method delegates to."""')
    lines.append("        self._client = client")
    for block in method_blocks:
        lines.append("")
        lines.extend(block)
    return "\n".join(lines) + "\n"
